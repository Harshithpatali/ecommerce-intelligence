"""
Streamlit CLV prediction page.

Features:
- Enter customer-level historical features.
- Call the FastAPI CLV prediction endpoint.
- Display predicted future revenue.
- Provide a compact business interpretation.
- Keep inference logic in FastAPI rather than duplicating the model locally.
"""

from __future__ import annotations

import pandas as pd
import streamlit as st

from api_client import (
    APIClientError,
    api_client,
)


st.set_page_config(
    page_title="CLV Prediction | E-Commerce Intelligence",
    page_icon="🔮",
    layout="wide",
)


# ---------------------------------------------------------------------------
# HELPERS
# ---------------------------------------------------------------------------

@st.cache_data(ttl=300)
def load_model_info() -> dict:
    """Load CLV model metadata."""
    return api_client.model_info()


def money(value: float | int | None) -> str:
    """Format predicted revenue."""
    if value is None:
        return "—"

    value = float(value)

    if abs(value) >= 1_000_000:
        return f"₹{value / 1_000_000:.2f}M"

    if abs(value) >= 100_000:
        return f"₹{value / 100_000:.2f}L"

    if abs(value) >= 1_000:
        return f"₹{value / 1_000:.1f}K"

    return f"₹{value:,.0f}"


def value_band(value: float) -> str:
    """Provide a simple portfolio interpretation."""
    if value >= 100_000:
        return "Very High Value"

    if value >= 50_000:
        return "High Value"

    if value >= 20_000:
        return "Medium Value"

    return "Lower Value"


# ---------------------------------------------------------------------------
# HEADER
# ---------------------------------------------------------------------------

st.title("🔮 Customer Lifetime Value Prediction")

st.markdown(
    """
    Estimate a customer's future revenue contribution using the trained
    XGBoost CLV model exposed through the FastAPI backend.
    """
)

st.info(
    "The prediction is generated by the backend model. "
    "The Streamlit application does not load or retrain the model locally."
)


# ---------------------------------------------------------------------------
# MODEL INFORMATION
# ---------------------------------------------------------------------------

with st.expander("Model Information"):
    try:
        model_info = load_model_info()

        info_columns = st.columns(3)

        with info_columns[0]:
            st.metric(
                "Model",
                str(
                    model_info.get(
                        "model_name",
                        model_info.get(
                            "model",
                            "XGBoost",
                        ),
                    )
                ),
            )

        with info_columns[1]:
            metric_value = model_info.get(
                "validation_rmse"
            )

            st.metric(
                "Validation RMSE",
                (
                    f"{float(metric_value):,.2f}"
                    if metric_value is not None
                    else "—"
                ),
            )

        with info_columns[2]:
            r2 = model_info.get(
                "validation_r2"
            )

            st.metric(
                "Validation R²",
                (
                    f"{float(r2):.3f}"
                    if r2 is not None
                    else "—"
                ),
            )

        st.json(model_info)

    except APIClientError as exc:
        st.warning(
            "Model metadata could not be loaded."
        )
        st.caption(str(exc))


# ---------------------------------------------------------------------------
# INPUT FORM
# ---------------------------------------------------------------------------

st.subheader("Customer Historical Profile")

with st.form(
    "clv_prediction_form"
):
    col1, col2 = st.columns(2)

    with col1:
        historical_recency_days = st.number_input(
            "Historical Recency (days)",
            min_value=0.0,
            value=30.0,
            step=1.0,
            help=(
                "Number of days since the customer's most recent "
                "historical purchase."
            ),
        )

        historical_order_count = st.number_input(
            "Historical Order Count",
            min_value=0.0,
            value=3.0,
            step=1.0,
        )

        historical_revenue = st.number_input(
            "Historical Revenue",
            min_value=0.0,
            value=5000.0,
            step=500.0,
        )

        historical_item_count = st.number_input(
            "Historical Item Count",
            min_value=0.0,
            value=5.0,
            step=1.0,
        )

    with col2:
        historical_unique_products = st.number_input(
            "Historical Unique Products",
            min_value=0.0,
            value=4.0,
            step=1.0,
        )

        historical_average_order_value = st.number_input(
            "Historical Average Order Value",
            min_value=0.0,
            value=1666.67,
            step=100.0,
        )

        historical_average_items_per_order = st.number_input(
            "Historical Average Items / Order",
            min_value=0.0,
            value=1.67,
            step=0.1,
        )

        historical_orders_per_active_day = st.number_input(
            "Historical Orders / Active Day",
            min_value=0.0,
            value=0.10,
            step=0.01,
            format="%.4f",
        )

    submitted = st.form_submit_button(
        "🔮 Predict Customer Value",
        type="primary",
        use_container_width=True,
    )


# ---------------------------------------------------------------------------
# PREDICTION
# ---------------------------------------------------------------------------

if submitted:
    features = {
        "historical_recency_days": historical_recency_days,
        "historical_order_count": historical_order_count,
        "historical_revenue": historical_revenue,
        "historical_item_count": historical_item_count,
        "historical_unique_products": historical_unique_products,
        "historical_average_order_value": (
            historical_average_order_value
        ),
        "historical_average_items_per_order": (
            historical_average_items_per_order
        ),
        "historical_orders_per_active_day": (
            historical_orders_per_active_day
        ),
    }

    with st.spinner(
        "Generating CLV prediction..."
    ):
        try:
            result = api_client.predict_customer(
                features
            )

        except APIClientError as exc:
            st.error(
                "Prediction failed."
            )
            st.code(str(exc))
            st.stop()

    # Try common response keys so this page remains compatible with the
    # prediction service's final response schema.
    prediction = result.get(
        "predicted_future_revenue"
    )

    if prediction is None:
        prediction = result.get(
            "prediction"
        )

    if prediction is None:
        prediction = result.get(
            "predicted_clv"
        )

    if prediction is None:
        st.error(
            "The API response did not contain a predicted future revenue value."
        )
        st.json(result)
        st.stop()

    prediction = float(prediction)

    st.divider()
    st.subheader("Prediction Result")

    result_col1, result_col2, result_col3 = st.columns(3)

    with result_col1:
        st.metric(
            "Predicted Future Revenue",
            money(prediction),
        )

    with result_col2:
        st.metric(
            "Value Band",
            value_band(prediction),
        )

    with result_col3:
        st.metric(
            "Historical Revenue",
            money(historical_revenue),
        )

    st.success(
        f"Estimated future customer value: {money(prediction)}"
    )

    st.subheader("Business Interpretation")

    interpretation = []

    if historical_order_count > 0:
        interpretation.append(
            "The customer has demonstrated prior purchasing activity."
        )

    if historical_revenue > 0:
        interpretation.append(
            "Historical revenue provides evidence of realized customer value."
        )

    if historical_recency_days <= 30:
        interpretation.append(
            "Recent purchasing activity suggests relatively strong recency."
        )
    elif historical_recency_days <= 90:
        interpretation.append(
            "The customer's recency is moderate and should be monitored."
        )
    else:
        interpretation.append(
            "High recency indicates that retention activity may deserve attention."
        )

    if prediction >= 50_000:
        interpretation.append(
            "The predicted future value is high enough to justify "
            "prioritized retention and personalization."
        )
    else:
        interpretation.append(
            "The predicted value can be combined with segmentation and "
            "retention signals before deciding on intervention priority."
        )

    for item in interpretation:
        st.write(f"• {item}")

    with st.expander("Prediction Payload"):
        st.json(result)


# ---------------------------------------------------------------------------
# INPUT REFERENCE
# ---------------------------------------------------------------------------

st.divider()

